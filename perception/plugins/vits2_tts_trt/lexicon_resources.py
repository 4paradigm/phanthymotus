"""Prepare the full external pronunciation resource before acoustic startup."""
from __future__ import annotations

import hashlib
import importlib.util
import json
import logging
import os
from pathlib import Path
import re
import tempfile
import threading

try:
    import fcntl
except ImportError:  # Development hosts; production Jetson uses process locks.
    fcntl = None


log = logging.getLogger(__name__)
_COMPILER_PATH = Path(__file__).resolve().parent / "lexicon_compiler.py"
_POLICY_PATH = Path(__file__).resolve().parent / "frontend/lexicon_case_policies.json"
_SOURCE_CANONICAL_SHA = "fd22474292e48b30b925521c227785dd24cefecf473d3d2d9044a31cb0bd2cfb"
_SOURCE_BASE = (
    "https://www.modelscope.cn/api/v1/models/lanxijiang/TTSV4_Ch_Eng/repo"
    "?Revision=e67fccc9fa0c2bd8848dcf93221e18bb3fa4f205&FilePath=frontend/{file}"
)
_SOURCE_FILES = {"en_gold_pronunciations.json": {
    "size": 672106,
    "sha256": "0c6fd2adb51aeae0fd83968f1902dedb16c73db695a3e3ad088bfc23cc05d57a",
}}
_SHA = re.compile(r"[0-9a-f]{64}\Z")
_THREAD_LOCK = threading.RLock()


def _sha(path):
    value = hashlib.sha256()
    with Path(path).open("rb") as source:
        for block in iter(lambda: source.read(1024 * 1024), b""):
            value.update(block)
    return value.hexdigest()


def _compiler():
    spec = importlib.util.spec_from_file_location("_vits2_external_lexicon_compiler", _COMPILER_PATH)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _validate(path, checksum):
    from .frontend.external_lexicon import validate_external_lexicon_file
    return validate_external_lexicon_file(path, checksum)


def _download(root, progress_cb):
    from utils.model_downloader import ensure_verified_bundle
    paths = ensure_verified_bundle("vits2-external-lexicon-source", str(root / "frontend"),
                                   _SOURCE_BASE, _SOURCE_FILES, progress_cb=progress_cb)
    return Path(paths["en_gold_pronunciations.json"])


def _atomic_write(path, payload):
    """Publish whole files; a crash between JSON/sidecar causes a rebuild."""
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(prefix=".external-lexicon-", dir=path.parent,
                                         delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(payload)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(str(temporary), str(path))
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def _cache_matches(output, sidecar, fingerprints):
    try:
        metadata = json.loads(sidecar.read_text(encoding="utf-8"))
        return (isinstance(metadata, dict) and metadata.get("version") == 1
                and all(metadata.get(key) == value for key, value in fingerprints.items())
                and output.stat().st_size == metadata.get("compiled_bytes")
                and _sha(output) == metadata.get("compiled_sha256"))
    except (OSError, ValueError, TypeError):
        return False


def ensure_external_lexicon(root, *, progress_cb=None, stage_cb=None):
    """Use an explicit valid resource or prepare/reuse the pinned default.

    Explicit paths never fall back to a download. The default is protected by
    a cross-process lock and binds CMU, compiler, policy, and generated bytes.
    No acoustic model, engine, global environment, or source dictionary changes.
    """
    def stage(name):
        if stage_cb is not None:
            try:
                stage_cb(name)
            except Exception:
                log.debug("[vits2] external lexicon status callback failed", exc_info=True)

    stage("verify")
    root = Path(root).resolve()
    explicit = os.environ.get("VITS2_LEXICON_PATH", "").strip()
    checksum = os.environ.get("VITS2_LEXICON_SHA256", "").strip().lower()
    if checksum and not _SHA.fullmatch(checksum):
        raise ValueError("VITS2_LEXICON_SHA256 requires 64 hexadecimal digits")
    if explicit:
        selected = Path(explicit).expanduser().resolve()
        _validate(selected, checksum)
        return selected

    directory = root / "frontend_data"
    cmu_path = directory / "cmudict.rep"
    if not cmu_path.is_file():
        raise FileNotFoundError("VITS2 CMU source is missing: " + str(cmu_path))
    fingerprints = {
        "source_canonical_sha256": _SOURCE_CANONICAL_SHA,
        "cmu_file_sha256": _sha(cmu_path),
        "compiler_sha256": _sha(_COMPILER_PATH),
        "policy_file_sha256": _sha(_POLICY_PATH),
    }
    output, sidecar = directory / "external_lexicon.json", directory / "external_lexicon.meta.json"
    directory.mkdir(parents=True, exist_ok=True)
    stage("waiting")
    with _THREAD_LOCK, open(directory / ".external_lexicon.lock", "a+b") as lock:
        if fcntl is not None:
            fcntl.flock(lock.fileno(), fcntl.LOCK_EX)
        try:
            if _cache_matches(output, sidecar, fingerprints):
                stage("verify")
                _validate(output, checksum)
                return output
            stage("download")
            source = _download(root, progress_cb)
            stage("compile")
            compiler = _compiler()
            policies = compiler.read_json(_POLICY_PATH)
            payload, _audit = compiler.compile_lexicon(source, compiler.parse_cmu_rep(cmu_path),
                expected_source_canonical_sha256=_SOURCE_CANONICAL_SHA,
                case_policies=policies, cmu_source_sha256=fingerprints["cmu_file_sha256"])
            data = compiler.encode_payload(payload)
            generated_sha = hashlib.sha256(data).hexdigest()
            if checksum and generated_sha != checksum:
                raise ValueError("Compiled external lexicon SHA256 does not match VITS2_LEXICON_SHA256")
            metadata = {"version": 1, **fingerprints, "compiled_sha256": generated_sha,
                        "compiled_bytes": len(data), "source_sha256": payload["source"]["sha256"],
                        "entries": len(payload["entries"])}
            _atomic_write(output, data)
            from .frontend.external_lexicon import reload_external_lexicon
            reload_external_lexicon(path=output, checksum=checksum)
            stage("verify")
            _validate(output, checksum)
            _atomic_write(sidecar, json.dumps(metadata, sort_keys=True, indent=2).encode("utf-8") + b"\n")
            log.info("[vits2] prepared external lexicon entries=%d sha256=%s", metadata["entries"], generated_sha)
            return output
        finally:
            if fcntl is not None:
                fcntl.flock(lock.fileno(), fcntl.LOCK_UN)
